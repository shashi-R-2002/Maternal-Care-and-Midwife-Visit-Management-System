document.querySelectorAll('.role-pill').forEach(pill => {
    pill.addEventListener('click', function() {
        document.querySelectorAll('.role-pill').forEach(p => p.classList.remove('active'));
        this.classList.add('active');
    });
});

/* ── Show/hide password — Login ── */
const showLoginCb  = document.getElementById('showLoginPass');
const loginPassInp = document.getElementById('loginPass');
const loginEye     = document.getElementById('loginEye');
if (showLoginCb) showLoginCb.addEventListener('change', function() {
    loginPassInp.type = this.checked ? 'text' : 'password';
    loginEye.className = this.checked ? 'bi bi-eye-slash eye-toggle' : 'bi bi-eye eye-toggle';
});
if (loginEye) loginEye.addEventListener('click', function() {
    const t = loginPassInp.type === 'text';
    loginPassInp.type = t ? 'password' : 'text';
    loginEye.className = t ? 'bi bi-eye eye-toggle' : 'bi bi-eye-slash eye-toggle';
    if (showLoginCb) showLoginCb.checked = !t;
});


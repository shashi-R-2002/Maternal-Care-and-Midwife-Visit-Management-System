 let currentLang = 'en';
 function applyLang(lang) {
     const t = translations[lang];
    if (!t) return;
    currentLang = lang;

    /* Update body class for font-family swap */
    document.body.classList.remove('lang-si', 'lang-ta');
    if (lang === 'si') document.body.classList.add('lang-si');
    if (lang === 'ta') document.body.classList.add('lang-ta');

    /* Update html lang attr */
    document.documentElement.lang = lang;

    /* Translate all [data-i18n] elements (innerHTML — supports <em> tags) */
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) el.innerHTML = t[key];
    });

    /* Translate placeholders */
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) el.placeholder = t[key];
    });

    /* Update button label */
    const labels = { en: '🇬🇧 English', si: '🇱🇰 සිංහල', ta: '🇱🇰 தமிழ்' };
    document.getElementById('langLabel').textContent = labels[lang].replace(/^.{4}/, '').trim();
    // Simpler: just set the text
    document.getElementById('langLabel').textContent = lang === 'en' ? 'English' : lang === 'si' ? 'සිංහල' : 'தமிழ்';

    /* Highlight active option */
    document.querySelectorAll('.language-option').forEach(opt => {
        opt.classList.toggle('active-lang', opt.getAttribute('data-lang') === lang);
    });
}

/* ── Language click handler ── */
document.querySelectorAll('.language-option').forEach(item => {
    item.addEventListener('click', function(e) {
        e.preventDefault();
        applyLang(this.getAttribute('data-lang'));
    });
});

